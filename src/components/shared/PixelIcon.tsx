export type PixelIconName = keyof typeof GRIDS;

interface PixelIconProps {
  name: PixelIconName;
  /** tamaño en px (la grilla nativa es 16) */
  size?: number;
  /** color; por defecto hereda currentColor */
  color?: string;
  className?: string;
}

export default function PixelIcon({ name, size = 24, color, className }: PixelIconProps) {
  const grid = GRIDS[name]!;
  const fill = color ?? 'currentColor';
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 16 16"
      shapeRendering="crispEdges"
      aria-hidden="true"
      className={className}
      style={{ flexShrink: 0 }}
    >
      {grid.flatMap((row, y) =>
        [...row].map((cell, x) => {
          if (cell === '.') return null;
          return (
            <rect
              key={`${x}-${y}`}
              x={x}
              y={y}
              width={1}
              height={1}
              fill={fill}
              opacity={cell === '+' ? 0.55 : 1}
            />
          );
        }),
      )}
    </svg>
  );
}
